const String kRefundsBody = '''
1. THE IDEA

A purchase in Ivory is a ticket to a private performance. The
moment it reaches you it has been performed, so a change of
mind is not a refund. That is the rule, and the exceptions
below are real exceptions, not loopholes to argue through.

2. ALWAYS REFUNDED

A ticket that never arrived. You paid and nothing unlocked, or
it unlocked and will not open.

A double charge. Two payments for one thing, whatever caused
it.

A show pulled before you stepped in. You paid for something
that was then taken down before you could see or hear it.

A session the house could not attend. Full refund, or a new
time, whichever you prefer.

3. SESSIONS

A session you cannot make should be moved, not cancelled. The
reschedule button is on the session itself and costs nothing.

If you simply do not come, and do not move it, the time is
used. The house held that hour for you and turned others away.
After a small number of no-shows the booking privilege pauses;
the app tells you where you stand before that happens.

A session cut short by a failure on the house's side is either
finished later at your convenience or refunded for the part
you did not get.

4. MEMBERSHIP

A tier is paid for a period and runs to the end of that
period. Stopping a membership stops the next renewal; it does
not refund the period you are inside. If a tier is charged
after you stopped it, that is a double charge under section 2
and it comes back.

5. EXTENSIONS

Time added to a session that then could not be used, because
of a failure on the house's side, is refunded in full.

6. HOW TO ASK

Use the quiet door inside the app and choose "a payment or
refund". Tell the house what happened and quote the reference
number from your payment. Ask within the window shown on the
privacy, safety and terms page.

7. WHAT HAPPENS NEXT

The house replies, and serious things are dealt with the same
day. An approved refund goes back to the method you paid from,
within the number of days shown on that same page. The house
cannot send it anywhere else - that is a rule of the payment
system, not a preference.

8. IF YOU ARE NOT SATISFIED

Write to the Grievance Officer. If you are still not
satisfied, nothing here takes away your right to go to a
consumer forum under the Consumer Protection Act 2019.
''';

