const String kPrivacyTitle = 'Privacy';
const String kPrivacyUpdated = 'Last updated 9 October 2026';

const String kPrivacyBody = '''
1. THE SHORT VERSION

Ivory collects as little as it can get away with. Nothing is
sold. Nothing is handed to advertisers. There are no tracking
pixels and no advertising networks anywhere in this app.

2. WHAT IS COLLECTED

Your account: the email address or phone number you signed in
with, the name you chose to show, and your photograph if you
set one.

Your membership: which tier you hold, when it started and when
it renews.

Your payments: the amount, the date, the reference number you
type in after paying, and the screenshot if you send one. The
house never sees your card, your bank login or your UPI PIN -
those stay with your own bank and payment app.

Your activity in Ivory: what you have unlocked, which sessions
you have booked, how long a session lasted, and the messages
you send to the house.

Your device, for notifications only: a token from Google that
lets a message reach your phone. It identifies the phone, not
you, and it is deleted when you sign out.

3. WHAT IS NOT COLLECTED

No location. No contacts. No photo library. No microphone or
camera except during a session you joined yourself, and
nothing from them is recorded or stored. No browsing of other
apps. No advertising identifier.

4. WHY

To let you in, to show you what your membership includes, to
run the sessions you book, to confirm payments, to answer you
when you write, and to meet the record-keeping the law
requires of anyone taking money.

5. WHO ELSE SEES IT

Only the services that make the app work, and only the part
each needs: Supabase holds the database and sign-in; Google
Firebase delivers notifications; Agora carries the live audio
and video; Cloudflare R2 stores film and voice files;
Razorpay, where used, handles payment. Each is bound by its
own contract and none receives your information to use for its
own purposes.

No one else. Not an advertiser, not a data broker, not another
member. The only exception is a demand the house is legally
required to answer, and the house will tell you if that
happens unless forbidden.

6. CALLS ARE NOT RECORDED

Sessions are live only. No recording is made by the house, not
of video, not of audio. What was said exists only in the
memory of the two people who were there. Recording a session
yourself is forbidden by the terms of use.

7. HOW LONG IT IS KEPT

Your account details stay while the account exists. Payment
records are kept for eight years because tax law requires it.
Messages to the house are kept while the matter is open and
for a reasonable time after. Notification tokens die when you
sign out. Nothing is auto-deleted behind your back.

8. YOUR RIGHTS

You may ask what is held about you, ask for a mistake to be
corrected, ask for your account and its data to be erased, and
withdraw a consent you gave. Ask through the quiet door or
write to the Grievance Officer. The house answers within 30
days, and usually the same day.

Erasure removes what the law allows to be removed. Payment
records stay for the eight years mentioned above - the house
is not permitted to delete those.

9. CHILDREN

Ivory is for adults. The house does not knowingly hold the
data of anyone under 18, and deletes it on discovery.

10. SECURITY

Everything travels encrypted. Access to the database is
restricted by rules that run on the server, not in the app, so
one member can never read another's rows. No system is beyond
failure; if one happens and it affects you, the house will
tell you and tell the authorities, as the law requires.

11. WHERE IT LIVES

Data is stored on servers operated by the providers in section
5, which may be outside India. They are bound to protect it to
the standard described here.

12. CHANGES

If this notice changes, the date at the top changes and the
app says so.

13. WHO TO ASK

The Grievance Officer named on the privacy, safety and terms
page. A real person, and the only address the house uses for
this.
''';

